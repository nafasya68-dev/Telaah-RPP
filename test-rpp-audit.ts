async function runTest() {
  console.log('=== MEMULAI PENGUJIAN 3 DOKUMEN RPP DENGAN GEMINI API ===\n');

  const testCases = [
    { name: 'RPP 1 (Lengkap & Komprehensif)', text: RPP_1_LENGKAP, file: 'RPP_1_Biologi_Lengkap.docx' },
    { name: 'RPP 2 (Sebagian / Belum Optimal)', text: RPP_2_SEBAGIAN, file: 'RPP_2_Matematika_Sebagian.docx' },
    { name: 'RPP 3 (Tanpa Komponen Opsional)', text: RPP_3_TANPA_OPSIONAL, file: 'RPP_3_Sosiologi_TanpaOpsional.docx' },
  ];

  for (const tc of testCases) {
    console.log(`\n--------------------------------------------------`);
    console.log(`Menguji: ${tc.name} [File: ${tc.file}]`);
    console.log(`--------------------------------------------------`);

    const start = Date.now();
    try {
      const res = await fetch('http://localhost:3000/api/analyze-rpp', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          fileName: tc.file,
          documentText: tc.text,
          reviewerName: 'Dr. H. Mulyono, M.Pd.',
          reviewerNip: '19680315 199303 1 002',
          aiConfig: {
            enabled: true,
            model: 'gemini-3.8-flash',
            strictness: 'standar',
            focus: 'seimbang',
          },
        }),
      });

      const duration = Date.now() - start;
      const json = await res.json();

      if (!json.success) {
        console.error(`FAILED: ${json.error}`);
        continue;
      }

      const summary = json.data.summary;
      const indicators = json.data.indicators;

      console.log(`Hasil Telaah Berhasil dalam ${duration}ms!`);
      console.log(`Request ID: ${json.requestId}`);
      console.log(`Mesin AI: ${json.engine}`);
      console.log(`Guru: ${json.data.identity.teacherName} | Satuan Pendidikan: ${json.data.identity.school}`);
      console.log(`Total Indikator: ${summary.totalIndicators}`);
      console.log(`Indikator Dinilai (Evaluated): ${summary.evaluatedCount}`);
      console.log(`Indikator N/A (Opsional): ${summary.naCount}`);
      console.log(`Jumlah Skor 2 (Optimal): ${summary.scoreCounts.score2}`);
      console.log(`Jumlah Skor 1 (Sebagian): ${summary.scoreCounts.score1}`);
      console.log(`Jumlah Skor 0 (Belum Terpenuhi): ${summary.scoreCounts.score0}`);
      console.log(`Total Skor Perolehan: ${summary.totalScore}`);
      console.log(`Penyebut Maksimal (Denominator): ${summary.maxPossibleScore}`);
      console.log(`Nilai Akhir: ${summary.finalScore} / 100`);
      console.log(`Predikat: ${summary.predicate}`);
      console.log(`Kategori Tindak Lanjut: ${summary.followUpCategory}`);

      // Check optional indicators scores
      const optIds = [2, 3, 10, 11, 22];
      const optStatuses = indicators
        .filter((ind: any) => optIds.includes(ind.id))
        .map((ind: any) => `#${ind.id} ${ind.name}: score=${ind.score}`);
      console.log(`Status 5 Indikator Opsional:\n  - ${optStatuses.join('\n  - ')}`);

    } catch (err: any) {
      console.error(`Exception during test: ${err.message}`);
    }
  }

  console.log('\n=== PENGUJIAN SELESAI ===');
}

runTest();
